#!/usr/bin/env python3
"""Generate extensions/twitch_integration/libraries/wares.xml — makes the Twitch
Allies an OWNER of the equipment their docks are supposed to sell.

    py -3 tools/gen_ware_owners.py "E:\\Steam\\steamapps\\common\\X4 Foundations"

Every ware in `libraries/wares.xml` carries an `<owner faction="…"/>` list: the
factions that have that ware. A faction in no list has nothing — which is why a
twitchally wharf listed ship hulls (built to order) and not one shield, engine,
weapon or piece of software.

Scope: wares whose `<restriction licence="…">` is one of LICENCES below. That is the
game's own definition of "standard equipment" and "military equipment", so it tracks
future ware additions instead of hard-coding a ware list.

ONE DELIBERATE EXCLUSION: wares owned ONLY by xenon/khaak. `militaryequipment`
includes Kha'ak and Xenon engines and turrets, and handing those to an Argon-flavoured
ally faction would put alien hardware on its shelves. Everything else in scope is
granted.

Unlike libraries/characters.xml, this diff uses `<add>`, which APPENDS `<owner>`
child elements — it never rewrites a vanilla list, so there is nothing here to drift
out of date when Egosoft changes one. Re-running after a game update simply picks up
newly added wares.
"""
from __future__ import annotations

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from gen_ships import all_cats, extract  # noqa: E402

# Faction(s) to grant the equipment to.
GRANT_TO = ["twitchally"]
# Which restriction licences count as "equipment this faction should stock".
# Add "capitalequipment" here for L/XL turrets and shields (15 more wares).
LICENCES = {"generaluseequipment", "militaryequipment"}
# Factions whose exclusive gear must NOT be granted.
ALIEN_ONLY = {"xenon", "khaak"}

OUT = (Path(__file__).resolve().parents[2]
       / "extensions" / "twitch_integration" / "libraries" / "wares.xml")

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!--
  GENERATED by bridge/tools/gen_ware_owners.py — do not hand-edit; re-run it instead.

  Makes the Twitch Allies an OWNER of standard and military equipment, so their
  wharfs, shipyards and equipment docks have shields, engines, weapons, turrets and
  software to sell. Every ware in libraries/wares.xml lists the factions that have
  it; twitchally was in none of them, so its docks offered ship hulls (which are
  built to order) and no equipment whatsoever.

  Scope is the game's own `<restriction licence="…">` — {licences} — rather than a
  hard-coded ware list, so it follows future ware additions.

  EXCLUDED: wares owned only by xenon/khaak. `militaryequipment` covers Kha'ak and
  Xenon engines and turrets, and alien hardware has no business on an Argon-flavoured
  ally's shelves.

  This diff uses <add>, which APPENDS an <owner> element (vanilla always keeps
  <owner> last inside <ware>, verified). It never rewrites a vanilla list, so unlike
  libraries/characters.xml there is nothing here that can drift when Egosoft edits
  one — re-run only to pick up new wares.
-->
<diff>
"""


def main() -> int:
    root = Path(sys.argv[1] if len(sys.argv) > 1
                else r"E:\Steam\steamapps\common\X4 Foundations")
    if not root.exists():
        print(f"X4 install not found: {root}")
        return 1

    # Base game + every DLC: each ships a wares.xml (full document or a <diff> that
    # adds more), and both shapes contain <ware> elements.
    wares: list[ET.Element] = []
    for cat in all_cats(root):
        blob = extract(cat, "libraries/wares.xml")
        if not blob:
            continue
        try:
            wares.extend(ET.fromstring(blob).iter("ware"))
        except ET.ParseError:
            continue
    if not wares:
        print("libraries/wares.xml not found in any archive")
        return 1

    lines: list[str] = []
    seen: set[str] = set()
    skipped_alien = 0
    for w in wares:
        wid = w.get("id")
        res = w.find("restriction")
        if not wid or wid in seen or res is None:
            continue
        if res.get("licence") not in LICENCES:
            continue
        seen.add(wid)
        owners = {o.get("faction") for o in w.findall("owner")}
        if owners and owners <= ALIEN_ONLY:
            skipped_alien += 1
            continue
        if all(f in owners for f in GRANT_TO):
            continue
        grants = "".join(f'<owner faction="{f}" />' for f in GRANT_TO if f not in owners)
        lines.append(f'  <add sel="/wares/ware[@id=\'{wid}\']">{grants}</add>')

    if not lines:
        print("no wares matched — check LICENCES")
        return 1

    OUT.write_text(HEADER.replace("{licences}", " + ".join(sorted(LICENCES)))
                   + "\n".join(lines) + "\n</diff>\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(lines)} wares granted to {', '.join(GRANT_TO)}; "
          f"{skipped_alien} xenon/khaak-only wares skipped)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
