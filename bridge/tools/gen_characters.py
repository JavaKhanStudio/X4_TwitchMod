#!/usr/bin/env python3
"""Generate extensions/twitch_integration/libraries/characters.xml — the diff that
gives the Twitch factions a POPULATION.

    py -3 tools/gen_characters.py "E:\\Steam\\steamapps\\common\\X4 Foundations"

Why this exists (found the hard way, x4debug.txt 2026-08-06):

    CharacterDB::FindNPCGenerator(): unable to find NPC generator for tags
    shiptrader, race null, factions Twitch Allies
    Error in MD cue md.NPC_Instantiation.PlaceItemTrader: Twitch Wharf has a trader
    corner but the faction has no character definition for a suitable trader [Owen]

X4 picks the NPC to stand at a post by looking up (tags, faction) in
`libraries/characters.xml`. Every `<character>` there carries
`<category tags="[…]" faction="[…]" race="…"/>`, and a faction that appears in NO
entry can have no people — the station builds, the control posts are requested, and
every single one comes back empty. `primaryrace="argon"` in factions.xml does NOT
help: the lookup is by faction, and it passed `race null`.

So: every character the ARGON factions can use, the Twitch factions can use too —
managers, ship traders, platform (trader-corner) traders, service crew, marines,
pilots, casuals, the lot. Both Twitch factions are `primaryrace="argon"` and reuse
Argon colours and icons already, so this is the consistent choice.

XML diffs cannot APPEND to an attribute, only replace it whole — which means this
file hard-codes vanilla's faction lists and would silently drop any faction Egosoft
adds to them in a patch. That is what this generator is for: re-run it after a game
update and the lists are correct again.
"""
from __future__ import annotations

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from gen_ships import all_cats, extract  # noqa: E402

# The factions to grant a population, and the vanilla faction whose character pool
# they inherit. Both Twitch factions are primaryrace="argon" (libraries/factions.xml).
TWITCH_FACTIONS = ["twitchally", "twitchfoe"]
INHERIT_FROM = "argon"

OUT = (Path(__file__).resolve().parents[2]
       / "extensions" / "twitch_integration" / "libraries" / "characters.xml")

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!--
  GENERATED by bridge/tools/gen_characters.py — do not hand-edit; re-run it instead
  (especially after an X4 update, see below).

  Gives the two Twitch factions a POPULATION. X4 resolves the NPC for a control post
  by looking up (tags, faction) in libraries/characters.xml; a faction named in no
  entry can have no people at all. Before this file, a twitchally station built fine
  and then stood empty — no manager, no ship dealer, no trader at the trade counter:

    CharacterDB::FindNPCGenerator(): unable to find NPC generator for tags
    shiptrader, race null, factions Twitch Allies
    md.NPC_Instantiation.PlaceItemTrader: Twitch Wharf has a trader corner but the
    faction has no character definition for a suitable trader [Owen]

  Note "race null" — primaryrace="argon" in factions.xml does not feed this lookup.

  What it does: every character entry the ARGON factions can draw on, the Twitch
  factions can draw on too. Both are primaryrace="argon" and already reuse Argon
  colours and icons, so they get Argon staff.

  MAINTENANCE: an XML diff cannot append to an attribute, only replace it whole, so
  the faction lists below are copies of the vanilla ones with our ids appended. An X4
  patch that adds a faction to one of these lists would be overwritten — re-run the
  generator after a game update.
-->
<diff>
"""


def main() -> int:
    root = Path(sys.argv[1] if len(sys.argv) > 1
                else r"E:\Steam\steamapps\common\X4 Foundations")
    if not root.exists():
        print(f"X4 install not found: {root}")
        return 1

    # Collect from EVERY archive, not just the last: the base game ships a full
    # <characters> document, while each DLC ships a <diff> that ADDS more entries to
    # it. Both shapes contain <character> elements, so iterating the whole tree picks
    # up DLC-added Argon staff as well as the base ones.
    entries: list[tuple[ET.Element, bool]] = []   # (character, came from a DLC)
    for cat in all_cats(root):
        b = extract(cat, "libraries/characters.xml")
        if not b:
            continue
        # A DLC's archive lives under extensions/<dlc>/; the base game's sits at the
        # install root. Characters a DLC adds don't exist for someone who lacks it.
        from_dlc = cat.parent.name.lower() != root.name.lower()
        try:
            entries.extend((c, from_dlc) for c in ET.fromstring(b).iter("character"))
        except ET.ParseError:
            continue
    if not entries:
        print("libraries/characters.xml not found in any archive")
        return 1

    lines: list[str] = []
    seen: set[str] = set()
    for c, from_dlc in entries:
        cid = c.get("id")
        cat_el = c.find("category")
        if cid is None or cat_el is None or cid in seen:
            continue
        raw = cat_el.get("faction")
        if not raw:
            continue
        seen.add(cid)
        facs = [f.strip() for f in raw.strip("[] ").split(",") if f.strip()]
        if INHERIT_FROM not in facs:
            continue
        merged = facs + [f for f in TWITCH_FACTIONS if f not in facs]
        # A DLC-defined character does not exist for someone who doesn't own that
        # DLC, and an unmatched `sel` is a load error. `silent` makes the miss a no-op.
        quiet = ' silent="true"' if from_dlc else ""
        sel = f"/characters/character[@id='{cid}']/category/@faction"
        lines.append(f'  <replace sel="{sel}"{quiet}>[{", ".join(merged)}]</replace>')

    if not lines:
        print(f"no character entries reference faction '{INHERIT_FROM}' — nothing written")
        return 1

    OUT.write_text(HEADER + "\n".join(lines) + "\n</diff>\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(lines)} character entries opened to "
          f"{', '.join(TWITCH_FACTIONS)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
